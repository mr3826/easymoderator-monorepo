'use strict';

/**
 * Versioned, proof-only semantic acceptance contract.
 *
 * This module is intentionally dependency-free. The migration proof mounts it
 * into its isolated candidate container, while the calibration runner imports
 * the same pure derivation helpers. It must never be imported by production
 * retrieval code.
 */

const SEMANTIC_ACCEPTANCE_VERSION = 'gemini-embedding-2-retrieval-v2';
const ACCEPTANCE_PROVIDER = 'gemini';
const ACCEPTANCE_MODEL = 'gemini-embedding-2';
const ACCEPTANCE_DIMENSIONS = 384;
const ACCEPTANCE_EMBEDDING_SPACE_VERSION = 'gemini-embedding-2-search-v1';
const POSITIVE_SCORE_MIN = 0.25;
const NEGATIVE_ACCEPTANCE_MODE = 'HYBRID_SEPARATION_BAND';
const CALIBRATION_MIN_DOCUMENTS = 20;
const CALIBRATION_MIN_POSITIVE_QUERIES = 30;
const CALIBRATION_MIN_NEGATIVE_QUERIES = 30;
const MINIMUM_SAFE_GAP = 0.10;
const NEGATIVE_SAFETY_MARGIN = 0.05;

// This is updated only when the controlled fixture corpus changes. It is a
// static binding so the proof cannot silently accept calibration for another
// corpus. The value is generated by semantic-calibration-fixtures.js.
const CONTROLLED_FIXTURE_VERSION = 'sha256:f306b317ec91678376e2813e1f31efa8c4a46e16b6f218e4b72820d0b8dae038';

const isFiniteNumber = (value) => Number.isFinite(Number(value));

function roundUp(value, decimalPlaces = 3) {
    if (!isFiniteNumber(value)) return null;
    const factor = 10 ** decimalPlaces;
    return Number((Math.ceil((Number(value) - 1e-12) * factor) / factor).toFixed(decimalPlaces));
}

function percentile(values, fraction) {
    const finiteValues = values.map(Number).filter(Number.isFinite).sort((left, right) => left - right);
    if (!finiteValues.length) return null;
    const index = (finiteValues.length - 1) * fraction;
    const lower = Math.floor(index);
    const upper = Math.ceil(index);
    if (lower === upper) return finiteValues[lower];
    return finiteValues[lower] + ((finiteValues[upper] - finiteValues[lower]) * (index - lower));
}

function finiteScores(values) {
    return values.map(Number).filter(Number.isFinite);
}

function deriveNegativeAcceptance({
    documents = [],
    positiveCases = [],
    negativeCases = [],
    positiveThreshold = POSITIVE_SCORE_MIN,
    safetyMargin = NEGATIVE_SAFETY_MARGIN,
    minimumSafeGap = MINIMUM_SAFE_GAP,
    minDocuments = CALIBRATION_MIN_DOCUMENTS,
    minPositiveQueries = CALIBRATION_MIN_POSITIVE_QUERIES,
    minNegativeQueries = CALIBRATION_MIN_NEGATIVE_QUERIES,
} = {}) {
    const positiveScores = finiteScores(positiveCases.map((item) => item.expectedScore));
    const negativeScores = finiteScores(negativeCases.map((item) => item.topScore));
    const positiveRankPass = positiveCases.length > 0
        && positiveCases.every((item) => item.expectedSourceExists !== false
            && Number(item.expectedRank ?? item.expectedSourceRank) === 1
            && Number(item.expectedScore) >= positiveThreshold);
    const negativeLexicalPass = negativeCases.length > 0
        && negativeCases.every((item) => {
            const overlap = Array.isArray(item.lexicalOverlap)
                ? item.lexicalOverlap
                : item.lexicalOverlap ? [item.lexicalOverlap] : [];
            return overlap.length === 0;
        });
    const counts = {
        documents: documents.length,
        positiveQueries: positiveCases.length,
        negativeQueries: negativeCases.length,
    };
    const minimumCountsPass = counts.documents >= minDocuments
        && counts.positiveQueries >= minPositiveQueries
        && counts.negativeQueries >= minNegativeQueries;
    const positiveFloorP05 = percentile(positiveScores, 0.05);
    const negativeMaximum = negativeScores.length ? Math.max(...negativeScores) : null;
    const observedScoreGap = isFiniteNumber(positiveFloorP05) && isFiniteNumber(negativeMaximum)
        ? positiveFloorP05 - negativeMaximum
        : null;
    const candidateCeiling = isFiniteNumber(negativeMaximum)
        ? roundUp(Number(negativeMaximum) + Number(safetyMargin))
        : null;
    const candidateSafetyGap = isFiniteNumber(positiveFloorP05) && isFiniteNumber(candidateCeiling)
        ? positiveFloorP05 - candidateCeiling
        : null;
    const separationPass = isFiniteNumber(candidateSafetyGap) && candidateSafetyGap >= minimumSafeGap;
    const ready = minimumCountsPass && positiveRankPass && negativeLexicalPass && separationPass;
    let status = 'PENDING_RECALIBRATION';
    if (!minimumCountsPass) status = 'INSUFFICIENT_CALIBRATION_EVIDENCE';
    else if (!positiveRankPass) status = 'POSITIVE_RANKING_FAILURE';
    else if (!negativeLexicalPass) status = 'NEGATIVE_FIXTURE_LEXICAL_OVERLAP';
    else if (!separationPass) status = 'OVERLAPPING_SCORE_DISTRIBUTIONS';
    if (ready) status = 'READY';

    return {
        status,
        ready,
        negativeCeiling: ready ? candidateCeiling : null,
        positiveFloorP05,
        negativeMaximum,
        observedScoreGap,
        candidateSafetyGap,
        minimumSafeGap,
        safetyMargin,
        counts,
        positiveRankPass,
        negativeLexicalPass,
        minimumCountsPass,
        derivation: {
            method: 'negative maximum plus explicit safety margin, bounded by positive P05 and minimum safe gap',
            negativeMaximum,
            safetyMargin,
            candidateCeiling,
            positiveFloorP05,
            minimumSafeGap,
            minimumCounts: {
                documents: minDocuments,
                positiveQueries: minPositiveQueries,
                negativeQueries: minNegativeQueries,
            },
            status,
        },
    };
}

const PROOF_ACCEPTANCE_CONTRACT = Object.freeze({
    schema_version: 1,
    semantic_acceptance_version: SEMANTIC_ACCEPTANCE_VERSION,
    provider: ACCEPTANCE_PROVIDER,
    model: ACCEPTANCE_MODEL,
    dimensions: ACCEPTANCE_DIMENSIONS,
    embedding_space_version: ACCEPTANCE_EMBEDDING_SPACE_VERSION,
    fixture_version: CONTROLLED_FIXTURE_VERSION,
    positive_threshold: POSITIVE_SCORE_MIN,
    negative_acceptance_mode: NEGATIVE_ACCEPTANCE_MODE,
    negative_ceiling: null,
    positive_floor_p05: null,
    minimum_safe_gap: MINIMUM_SAFE_GAP,
    safety_margin: NEGATIVE_SAFETY_MARGIN,
    status: 'PENDING_RECALIBRATION',
    threshold_derivation: {
        method: 'negative maximum plus safety margin; activated only after expanded 384-dimensional calibration',
        minimum_documents: CALIBRATION_MIN_DOCUMENTS,
        minimum_positive_queries: CALIBRATION_MIN_POSITIVE_QUERIES,
        minimum_negative_queries: CALIBRATION_MIN_NEGATIVE_QUERIES,
        minimum_safe_gap: MINIMUM_SAFE_GAP,
        safety_margin: NEGATIVE_SAFETY_MARGIN,
    },
    calibration_run_id: null,
    calibration_commit_sha: null,
    workflow_run_id: null,
    generated_at: null,
});

function acceptanceError(code, message) {
    const error = new Error(message);
    error.name = code;
    error.code = code;
    return error;
}

function hasCalibrationProvenance(contract) {
    const commitSha = String(contract?.calibration_commit_sha || '');
    const workflowRunId = String(contract?.workflow_run_id || '');
    const calibrationRunId = String(contract?.calibration_run_id || '');
    const generatedAt = String(contract?.generated_at || '');
    const derivation = contract?.threshold_derivation;
    return /^\b[0-9a-f]{40}\b$/iu.test(commitSha)
        && calibrationRunId.length > 0
        && workflowRunId.length > 0
        && Number.isFinite(Date.parse(generatedAt))
        && derivation
        && typeof derivation.method === 'string'
        && Number.isFinite(Number(derivation.negativeMaximum))
        && Number.isFinite(Number(derivation.candidateCeiling))
        && Number.isFinite(Number(derivation.positiveFloorP05))
        && Number(derivation.candidateCeiling) === Number(contract.negative_ceiling)
        && Number(derivation.positiveFloorP05) === Number(contract.positive_floor_p05);
}

function assertAcceptanceContract(contract, identity) {
    if (!contract || typeof contract !== 'object') {
        throw acceptanceError('SEMANTIC_CALIBRATION_NOT_READY', 'semantic acceptance contract is missing');
    }
    const expectedIdentity = {
        provider: String(identity?.provider || ''),
        model: String(identity?.model || ''),
        dimensions: Number(identity?.dimensions),
        embedding_space_version: String(identity?.embedding_space_version || ''),
    };
    for (const field of ['provider', 'model', 'dimensions', 'embedding_space_version']) {
        if (String(contract[field]) !== String(expectedIdentity[field])) {
            throw acceptanceError('EMBEDDING_SPACE_MISMATCH', `semantic acceptance identity mismatch: ${field}`);
        }
    }
    if (contract.semantic_acceptance_version !== SEMANTIC_ACCEPTANCE_VERSION
        || contract.fixture_version !== CONTROLLED_FIXTURE_VERSION) {
        throw acceptanceError('SEMANTIC_ACCEPTANCE_STALE', 'semantic acceptance provenance is stale');
    }
    if (contract.status !== 'READY'
        || !isFiniteNumber(contract.negative_ceiling)
        || !isFiniteNumber(contract.positive_floor_p05)) {
        throw acceptanceError('SEMANTIC_CALIBRATION_NOT_READY', 'semantic calibration is not ready for proof acceptance');
    }
    if (!hasCalibrationProvenance(contract)) {
        throw acceptanceError('SEMANTIC_ACCEPTANCE_STALE', 'active semantic acceptance lacks calibration provenance');
    }
    if (contract.negative_acceptance_mode !== NEGATIVE_ACCEPTANCE_MODE
        || Number(contract.positive_threshold) !== POSITIVE_SCORE_MIN
        || Number(contract.minimum_safe_gap) < MINIMUM_SAFE_GAP
        || Number(contract.positive_floor_p05) - Number(contract.negative_ceiling) < Number(contract.minimum_safe_gap)
        || Number(contract.negative_ceiling) >= Number(contract.positive_floor_p05)) {
        throw acceptanceError('SEMANTIC_ACCEPTANCE_STALE', 'semantic acceptance safety boundary is invalid');
    }
    return true;
}

function createCalibratedContract({
    candidate,
    calibrationRunId,
    calibrationCommitSha,
    workflowRunId,
    generatedAt,
    fixtureVersion = CONTROLLED_FIXTURE_VERSION,
    provider = ACCEPTANCE_PROVIDER,
    model = ACCEPTANCE_MODEL,
    dimensions = ACCEPTANCE_DIMENSIONS,
    embeddingSpaceVersion = ACCEPTANCE_EMBEDDING_SPACE_VERSION,
} = {}) {
    if (!candidate || candidate.status !== 'READY'
        || !isFiniteNumber(candidate.negativeCeiling)
        || !isFiniteNumber(candidate.positiveFloorP05)) {
        throw acceptanceError('SEMANTIC_CALIBRATION_NOT_READY', 'calibration candidate is not ready');
    }
    if (provider !== ACCEPTANCE_PROVIDER
        || model !== ACCEPTANCE_MODEL
        || Number(dimensions) !== ACCEPTANCE_DIMENSIONS
        || embeddingSpaceVersion !== ACCEPTANCE_EMBEDDING_SPACE_VERSION
        || fixtureVersion !== CONTROLLED_FIXTURE_VERSION) {
        throw acceptanceError('SEMANTIC_ACCEPTANCE_STALE', 'calibration candidate identity is not current');
    }
    const contract = {
        ...PROOF_ACCEPTANCE_CONTRACT,
        provider,
        model,
        dimensions: Number(dimensions),
        embedding_space_version: embeddingSpaceVersion,
        fixture_version: fixtureVersion,
        status: 'READY',
        negative_ceiling: Number(candidate.negativeCeiling),
        positive_floor_p05: Number(candidate.positiveFloorP05),
        threshold_derivation: {
            ...(candidate.derivation || {}),
            status: 'READY',
            candidateCeiling: Number(candidate.negativeCeiling),
            positiveFloorP05: Number(candidate.positiveFloorP05),
        },
        calibration_run_id: String(calibrationRunId || workflowRunId || ''),
        calibration_commit_sha: String(calibrationCommitSha || ''),
        workflow_run_id: String(workflowRunId || ''),
        generated_at: String(generatedAt || ''),
    };
    assertAcceptanceContract(contract, {
        provider,
        model,
        dimensions,
        embedding_space_version: embeddingSpaceVersion,
    });
    return Object.freeze(contract);
}

function evaluatePositiveCase({ expectedRank, expectedScore, contract = PROOF_ACCEPTANCE_CONTRACT } = {}) {
    const pass = Number(expectedRank) === 1
        && isFiniteNumber(expectedScore)
        && Number(expectedScore) >= Number(contract?.positive_threshold ?? POSITIVE_SCORE_MIN);
    return {
        pass,
        reason: pass ? 'NONE' : Number(expectedRank) !== 1 ? 'EXPECTED_SOURCE_NOT_TOP' : 'EXPECTED_SCORE_BELOW_THRESHOLD',
    };
}

function evaluateNegativeCase({ topScore = null, lexicalOverlap = false, contract = PROOF_ACCEPTANCE_CONTRACT } = {}) {
    if (!contract || contract.status !== 'READY' || !isFiniteNumber(contract.negative_ceiling)) {
        return { pass: false, reason: 'SEMANTIC_CALIBRATION_NOT_READY' };
    }
    if (lexicalOverlap) return { pass: false, reason: 'NEGATIVE_FIXTURE_LEXICAL_OVERLAP' };
    if (topScore === null || topScore === undefined) return { pass: true, reason: 'NONE' };
    const pass = isFiniteNumber(topScore) && Number(topScore) <= Number(contract.negative_ceiling);
    return { pass, reason: pass ? 'NONE' : 'NEGATIVE_RESULT_ABOVE_CALIBRATED_CEILING' };
}

function contractForIdentity(identity) {
    if (identity?.provider === ACCEPTANCE_PROVIDER
        && identity?.model === ACCEPTANCE_MODEL
        && Number(identity?.dimensions) === ACCEPTANCE_DIMENSIONS
        && identity?.embedding_space_version === ACCEPTANCE_EMBEDDING_SPACE_VERSION) {
        return PROOF_ACCEPTANCE_CONTRACT;
    }
    return Object.freeze({
        ...PROOF_ACCEPTANCE_CONTRACT,
        provider: identity?.provider || 'unknown',
        model: identity?.model || 'unknown',
        dimensions: Number(identity?.dimensions),
        embedding_space_version: identity?.embedding_space_version || 'unknown',
        status: 'PENDING_RECALIBRATION',
        fixture_version: CONTROLLED_FIXTURE_VERSION,
        negative_ceiling: null,
        positive_floor_p05: null,
    });
}

